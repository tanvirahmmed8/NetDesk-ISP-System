CREATE TABLE IF NOT EXISTS pops (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL UNIQUE,
 type VARCHAR(40) NOT NULL DEFAULT 'own', district VARCHAR(100) NULL, upazila VARCHAR(100) NULL
);
CREATE TABLE IF NOT EXISTS teams (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL UNIQUE,
 pop_id INT UNSIGNED NULL, description TEXT NULL,
 FOREIGN KEY(pop_id) REFERENCES pops(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS employees (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL,phone VARCHAR(40) NOT NULL,
 email VARCHAR(150) NULL,role VARCHAR(60) NOT NULL DEFAULT 'support',team_id INT UNSIGNED NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, FOREIGN KEY(team_id) REFERENCES teams(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS issue_types (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL UNIQUE,
 category VARCHAR(30) NOT NULL DEFAULT 'other',kind VARCHAR(30) NOT NULL DEFAULT 'support',active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS customer_followups (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,customer_id INT UNSIGNED NOT NULL,
 note TEXT NOT NULL,outcome VARCHAR(40) NOT NULL DEFAULT 'note',employee_id INT UNSIGNED NULL,
 occurred_at DATETIME NULL,next_follow_up_at DATETIME NULL,promised_payment_date DATE NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE CASCADE,
 FOREIGN KEY(employee_id) REFERENCES employees(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS invoices (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,invoice_no VARCHAR(60) NOT NULL UNIQUE,customer_id INT UNSIGNED NOT NULL,
 period VARCHAR(7) NULL,due_date DATE NULL,mrc DECIMAL(10,2) NOT NULL,otc DECIMAL(10,2) NOT NULL DEFAULT 0,
 discount DECIMAL(10,2) NOT NULL DEFAULT 0,amount DECIMAL(10,2) NOT NULL,notes TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS payments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,invoice_id INT UNSIGNED NOT NULL,
 amount DECIMAL(10,2) NOT NULL,method VARCHAR(30) NOT NULL DEFAULT 'cash',reference VARCHAR(150) NULL,
 paid_at DATETIME NOT NULL,employee_id INT UNSIGNED NULL,notes TEXT NULL,
 FOREIGN KEY(invoice_id) REFERENCES invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY(employee_id) REFERENCES employees(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS activity_events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,entity VARCHAR(30) NOT NULL,record_key VARCHAR(100) NOT NULL,
 action VARCHAR(50) NOT NULL,actor_id INT UNSIGNED NULL,actor_name VARCHAR(150) NULL,note TEXT NULL,
 before_data JSON NULL,after_data JSON NULL,occurred_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_activity_record(entity,record_key,id)
);
CREATE TABLE IF NOT EXISTS report_import_batches (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,kind VARCHAR(30) NOT NULL,filename VARCHAR(200) NOT NULL,
 options JSON NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS report_import_rows (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,batch_id INT UNSIGNED NOT NULL,source_row INT NOT NULL,
 original_data JSON NOT NULL,payload JSON NOT NULL,issues JSON NOT NULL,
 state VARCHAR(30) NOT NULL DEFAULT 'needs_review',result JSON NULL,
 FOREIGN KEY(batch_id) REFERENCES report_import_batches(id) ON DELETE CASCADE,
 INDEX idx_import_state(batch_id,state,id)
);
